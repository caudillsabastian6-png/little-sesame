# Runs on the bridge PC only. Generates the bridge shared token and writes:
#   config.json          (bridge config, next to this script)
#   ../cores3/sketch/potion_v121/bridge_secrets.h  (firmware build config)
# The token itself is never printed -- only confirmation lines.
import json
import os
import secrets

BRIDGE_DIR = os.path.dirname(os.path.abspath(__file__))
SKETCH_DIR = os.path.join(os.path.dirname(BRIDGE_DIR), "cores3", "sketch", "potion_v121")  # adjust to your firmware tree
HOST = "YOUR-BRIDGE-LAN-IP"  # the bridge PC's address on your home network
PORT = 8377

token = secrets.token_hex(24)

os.makedirs(BRIDGE_DIR, exist_ok=True)
os.makedirs(SKETCH_DIR, exist_ok=True)

with open(os.path.join(BRIDGE_DIR, "config.json"), "w", encoding="utf-8") as f:
    json.dump({"host": HOST, "port": PORT, "token": token}, f, indent=2)

header = (
    "// Generated by gen_config.py -- local build config, never commit.\n"
    "#pragma once\n"
    '#define BRIDGE_HOST "%s"\n'
    "#define BRIDGE_PORT %d\n"
    '#define BRIDGE_TOKEN "%s"\n'
) % (HOST, PORT, token)
with open(os.path.join(SKETCH_DIR, "bridge_secrets.h"), "w", encoding="utf-8") as f:
    f.write(header)

print("config.json written (token not shown)")
print("bridge_secrets.h written (token not shown)")
